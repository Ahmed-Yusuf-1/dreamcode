/**
 * Writes the database's copy of the reward rules from the curriculum, so the
 * server awards exactly what the app shows:
 *
 *   supabase/seed/activity_rewards.sql   XP per activity
 *   supabase/seed/badge_catalog.sql      what every activity is, every badge,
 *                                        its rarity bonus and its rule
 *
 * Run with `npm run seed:rewards` after any content change, then run both files
 * in the Supabase SQL editor. `npm test` fails if a committed file is stale.
 */
const fs = require("node:fs");
const path = require("node:path");
const { loadTs, root } = require("./lib/load-ts.cjs");

const REWARDS_OUTPUT = path.join(root, "supabase", "seed", "activity_rewards.sql");
const BADGES_OUTPUT = path.join(root, "supabase", "seed", "badge_catalog.sql");

const quote = (value) => `'${String(value).replace(/'/g, "''")}'`;
const quoteOrNull = (value) => (value === null || value === undefined ? "null" : quote(value));

function activityKeys(catalog) {
  return [
    ...catalog.lessons.map((l) => l.slug),
    ...catalog.lessons.filter((l) => l.practiceSlug).map((l) => `practice:${l.practiceSlug}`),
    ...catalog.challenges.map((c) => c.slug),
    ...catalog.projects.map((p) => p.id),
  ].sort();
}

function buildSql() {
  const { buildCatalog } = loadTs("src/lib/catalog.server.ts");
  const { getActivityReward } = loadTs("src/lib/rewards.ts");
  const catalog = buildCatalog();
  const rows = activityKeys(catalog).map((key) => {
    const reward = getActivityReward(key, catalog);
    if (!reward) throw new Error(`No reward for ${key}`);
    return `  (${quote(key)}, ${reward.xp})`;
  });
  return [
    "-- GENERATED by scripts/generate-reward-seed.cjs. Do not edit by hand.",
    "-- Run after migrations/0004_badges_leaderboard.sql, and again whenever the",
    "-- curriculum changes (npm run seed:rewards regenerates this file).",
    "begin;",
    "delete from public.activity_rewards;",
    "insert into public.activity_rewards (activity_key, xp) values",
    rows.join(",\n") + ";",
    "commit;",
    "",
  ].join("\n");
}

function buildBadgeSql() {
  const { buildCatalog } = loadTs("src/lib/catalog.server.ts");
  const { buildActivityMeta } = loadTs("src/lib/activityMeta.ts");
  const { RARITY, expandKeys } = loadTs("src/lib/badges.ts");
  const catalog = buildCatalog();

  const meta = buildActivityMeta(catalog);
  const metaRows = [...meta.entries()]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([key, m]) => `  (${quote(key)}, ${quote(m.kind)}, ${quoteOrNull(m.track)}, ${quoteOrNull(m.tier)})`);

  const badgeRows = [];
  const requirementRows = [];
  for (const badge of catalog.badges) {
    // The database only needs the rule's conditions; the key set it asks for is
    // expanded here into badge_requirements, so Postgres never reads content.
    const rule = { ...badge.rule };
    if (rule.keys) {
      for (const key of expandKeys(rule.keys.source, catalog)) {
        requirementRows.push(`  (${quote(badge.id)}, ${quote(key)})`);
      }
      rule.keys = { mode: rule.keys.mode };
    }
    badgeRows.push(`  (${quote(badge.id)}, ${quote(badge.rarity)}, ${RARITY[badge.rarity].xp}, ${quote(JSON.stringify(rule))}::jsonb)`);
  }

  return [
    "-- GENERATED by scripts/generate-reward-seed.cjs. Do not edit by hand.",
    "-- What every activity is, and every badge with the rule that unlocks it.",
    "-- Run after migrations/0004_badges_leaderboard.sql, and again whenever the",
    "-- curriculum or the badge list changes (npm run seed:rewards).",
    "begin;",
    "delete from public.activity_meta;",
    "insert into public.activity_meta (activity_key, kind, track, tier) values",
    metaRows.join(",\n") + ";",
    "",
    "delete from public.badge_requirements;",
    "delete from public.badge_catalog;",
    "insert into public.badge_catalog (badge_id, rarity, xp, rule) values",
    badgeRows.join(",\n") + ";",
    "",
    requirementRows.length > 0
      ? "insert into public.badge_requirements (badge_id, activity_key) values\n" + requirementRows.join(",\n") + ";"
      : "-- no key-based badge rules",
    "commit;",
    "",
  ].join("\n");
}

module.exports = { buildSql, buildBadgeSql, OUTPUT: REWARDS_OUTPUT, BADGES_OUTPUT };

if (require.main === module) {
  fs.mkdirSync(path.dirname(REWARDS_OUTPUT), { recursive: true });
  fs.writeFileSync(REWARDS_OUTPUT, buildSql());
  fs.writeFileSync(BADGES_OUTPUT, buildBadgeSql());
  console.log(`Wrote ${path.relative(root, REWARDS_OUTPUT)} and ${path.relative(root, BADGES_OUTPUT)}`);
}
